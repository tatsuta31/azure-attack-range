"""Make a small Splunk app that applies the Sysmon TA's CIM mapping to classic (non-XML) Sysmon events.

Why: Splunk Add-on for Sysmon (Splunk_TA_microsoft_sysmon 5.x) only maps
source="XmlWinEventLog:Microsoft-Windows-Sysmon/Operational" (renderXml=1). Events forwarded
with renderXml=0 arrive as source="WinEventLog:Microsoft-Windows-Sysmon/Operational" and get
no eventtypes/tags (so they never enter the Endpoint data model) and no CIM fields
(process, process_name, parent_process, ...). ESCU's tstats rules then never fire.

This script copies the TA's own settings and points them at the classic source, so the
generated app follows the TA version you actually run. It does not ship any TA content:
run it against your installed copy of the TA.

Usage:
  python -I make_sysmon_classic_app.py <path to Splunk_TA_microsoft_sysmon> <output dir>

Output: <output dir>/TA-sysmon-classic-cim/ (default/app.conf, props.conf, eventtypes.conf,
tags.conf, metadata/default.meta). Install it on the search head(s) next to the Sysmon TA
and the Windows TA (the Windows TA extracts CommandLine, Image, ... from classic events).
Re-run it after upgrading the Sysmon TA.
"""
import os
import re
import sys

XML_SOURCE = "XmlWinEventLog:Microsoft-Windows-Sysmon/Operational"
CLASSIC_SOURCE = "WinEventLog:Microsoft-Windows-Sysmon/Operational"
APP = "TA-sysmon-classic-cim"
SUFFIX = "-classic"
# Index-time settings and the XML-only field extraction are not copied.
SKIP_KEYS = re.compile(r"^(TIME_PREFIX|TIME_FORMAT|TZ|REPORT-.*)$")
# Transforms in the TA whose regex does not depend on the XML layout (checked on TA 5.0.0).
# The XML-only ones (sysmon-data, sysmon-computer, sysmon-sid, sysmon-registryvalue*, ...)
# are replaced by the Windows TA's extraction of classic events.
FORMAT_AGNOSTIC_TRANSFORMS = [
    "sysmon-md5", "sysmon-sha1", "sysmon-sha256", "sysmon-imphash", "sysmon-filename",
    "sysmon-dns-answer-data", "sysmon-hostname-from-clientinfo", "sysmon-ConsumerNoQuotes",
    "sysmon-DestinationNoQuotes", "sysmon-FilterNoQuotes",
]


def read_stanzas(path):
    """Return [(stanza, [(key, raw_lines)])], keeping backslash continuation lines intact."""
    stanzas, cur, entries = [], None, None
    key, buf = None, []
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()

    def flush():
        nonlocal key, buf
        if key is not None and entries is not None:
            entries.append((key, buf))
        key, buf = None, []

    for line in lines:
        if buf and buf[-1].endswith("\\"):
            buf.append(line)
            continue
        flush()
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        if s.startswith("[") and s.endswith("]"):
            cur, entries = s[1:-1], []
            stanzas.append((cur, entries))
            continue
        if "=" in line and entries is not None:
            key = line.split("=", 1)[0].strip()
            buf = [line]
    flush()
    return stanzas


def main(ta_dir, out_dir):
    default = os.path.join(ta_dir, "default")
    stanzas = dict(read_stanzas(os.path.join(default, "props.conf")))
    src = stanzas.get(f"source::{XML_SOURCE}")
    if src is None:
        raise SystemExit(f"[source::{XML_SOURCE}] not found in props.conf")

    app = os.path.join(out_dir, APP)
    os.makedirs(os.path.join(app, "default"), exist_ok=True)
    os.makedirs(os.path.join(app, "metadata"), exist_ok=True)

    props = [f"# Generated by make_sysmon_classic_app.py from {os.path.basename(ta_dir)}",
             f"[source::{CLASSIC_SOURCE}]",
             "# Fields the TA's XML-only transforms would give, taken from classic events instead",
             "FIELDALIAS-sysmon_classic_computer = ComputerName AS Computer",
             "REPORT-sysmon_classic = " + ",".join(FORMAT_AGNOSTIC_TRANSFORMS)]
    copied = 0
    for key, raw in src:
        if SKIP_KEYS.match(key):
            continue
        props.extend(raw)
        copied += 1
    with open(os.path.join(app, "default", "props.conf"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(props) + "\n")

    et_out, tag_out, names = [], [], []
    for name, entries in read_stanzas(os.path.join(default, "eventtypes.conf")):
        for key, raw in entries:
            if key == "search" and XML_SOURCE in "\n".join(raw):
                names.append(name)
                et_out += [f"[{name}{SUFFIX}]"] + [r.replace(XML_SOURCE, CLASSIC_SOURCE) for r in raw] + [""]
    for name, entries in read_stanzas(os.path.join(default, "tags.conf")):
        m = re.match(r"eventtype=(.+)$", name)
        if m and m.group(1) in names:
            tag_out += [f"[eventtype={m.group(1)}{SUFFIX}]"] + [l for _, raw in entries for l in raw] + [""]
    with open(os.path.join(app, "default", "eventtypes.conf"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(et_out))
    with open(os.path.join(app, "default", "tags.conf"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(tag_out))

    with open(os.path.join(app, "default", "app.conf"), "w", encoding="utf-8", newline="\n") as f:
        f.write("[install]\nstate = enabled\n\n[ui]\nis_visible = false\n"
                "label = Sysmon classic (renderXml=0) CIM mapping\n\n[launcher]\nversion = 1.0.0\n"
                "description = Applies Splunk_TA_microsoft_sysmon CIM mapping to WinEventLog:Microsoft-Windows-Sysmon/Operational\n")
    with open(os.path.join(app, "metadata", "default.meta"), "w", encoding="utf-8", newline="\n") as f:
        f.write("[]\naccess = read : [ * ], write : [ admin ]\nexport = system\n")
    print(f"{app}: {copied} props settings, {len(names)} eventtypes")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
